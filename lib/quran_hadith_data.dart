class ReelsIslamiDesenPainter extends CustomPainter {
  final int desenTipi;
  final Color altinRenk;

  ReelsIslamiDesenPainter({required this.desenTipi, required this.altinRenk});

  @override
  void paint(Canvas canvas, Size size) {
    final cizgiPaint = Paint()
      ..color = altinRenk.withValues(alpha: 0.065)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.4;

    final tip = desenTipi % 8;
    if (tip == 0) {
      // 1. Sekiz Köşeli Rub el Hizb Geometrik Yıldız
      _rubElHizbCiz(canvas, Offset(size.width * 0.85, size.height * 0.14), 110, cizgiPaint);
      _rubElHizbCiz(canvas, Offset(size.width * 0.12, size.height * 0.86), 130, cizgiPaint);
    } else if (tip == 1) {
      // 2. Cami Kubbesi & Mihrap Kemeri Silüeti
      final kemer = Path()
        ..moveTo(size.width * 0.15, size.height)
        ..lineTo(size.width * 0.15, size.height * 0.32)
        ..quadraticBezierTo(size.width * 0.5, size.height * 0.06, size.width * 0.85, size.height * 0.32)
        ..lineTo(size.width * 0.85, size.height);
      canvas.drawPath(kemer, cizgiPaint);
    } else if (tip == 2) {
      // 3. Selçuklu 12 Köşeli Şemse Rozeti
      final merkez = Offset(size.width * 0.82, size.height * 0.18);
      for (int i = 0; i < 6; i++) {
        canvas.save();
        canvas.translate(merkez.dx, merkez.dy);
        canvas.rotate(i * math.pi / 6);
        canvas.drawRect(Rect.fromCenter(center: Offset.zero, width: 120, height: 120), cizgiPaint);
        canvas.restore();
      }
    } else if (tip == 3) {
      // 4. İç İçe Nur Halkaları
      canvas.drawCircle(Offset(size.width * 0.85, size.height * 0.15), 95, cizgiPaint);
      canvas.drawCircle(Offset(size.width * 0.85, size.height * 0.15), 135, cizgiPaint);
      canvas.drawCircle(Offset(size.width * 0.15, size.height * 0.85), 115, cizgiPaint);
    } else if (tip == 4) {
      // 5. Fas Zellige Elmas Kafesi
      for (int i = 0; i < 3; i++) {
        _rubElHizbCiz(
          canvas,
          Offset(size.width * (0.2 + i * 0.3), size.height * 0.12),
          65,
          cizgiPaint,
        );
      }
    } else if (tip == 5) {
      // 6. Çift Katmanlı Endülüs Kemeri
      for (final inset in [0.12, 0.18]) {
        final p = Path()
          ..moveTo(size.width * inset, size.height)
          ..lineTo(size.width * inset, size.height * 0.35)
          ..arcToPoint(
            Offset(size.width * (1 - inset), size.height * 0.35),
            radius: Radius.circular(size.width * 0.4),
          )
          ..lineTo(size.width * (1 - inset), size.height);
        canvas.drawPath(p, cizgiPaint);
      }
    } else if (tip == 6) {
      // 7. Sekizgen Kûfi Madalyon
      final m = Offset(size.width * 0.5, size.height * 0.5);
      canvas.drawCircle(m, size.width * 0.42, cizgiPaint);
      _rubElHizbCiz(canvas, m, size.width * 0.55, cizgiPaint);
    } else {
      // 8. Köşe Tezhip Çeyrek Gülleri
      canvas.drawCircle(Offset.zero, 140, cizgiPaint);
      canvas.drawCircle(Offset(size.width, 0), 140, cizgiPaint);
      canvas.drawCircle(Offset(0, size.height), 140, cizgiPaint);
      canvas.drawCircle(Offset(size.width, size.height), 140, cizgiPaint);
    }
  }

  void _rubElHizbCiz(Canvas canvas, Offset center, double r, Paint paint) {
    for (final a in [0.0, math.pi / 4]) {
      canvas.save();
      canvas.translate(center.dx, center.dy);
      canvas.rotate(a);
      canvas.drawRect(Rect.fromCenter(center: Offset.zero, width: r, height: r), paint);
      canvas.restore();
    }
    canvas.drawCircle(center, r * 0.25, paint);
  }

  @override
  bool shouldRepaint(covariant ReelsIslamiDesenPainter oldDelegate) =>
      oldDelegate.desenTipi != desenTipi;
}

